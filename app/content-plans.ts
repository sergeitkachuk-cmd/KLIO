export type AuthorPosition = "brand" | "expert" | "journalist" | "customer" | "neutral";

export function normalizeAuthorPosition(value: unknown, fallback: AuthorPosition = "neutral"): AuthorPosition {
  const normalized = typeof value === "string" ? value.trim().toLocaleLowerCase("ru-RU") : "";
  if (["brand", "бренд", "company", "компания"].includes(normalized)) return "brand";
  if (["expert", "эксперт"].includes(normalized)) return "expert";
  if (["journalist", "journal", "журналист", "редакция"].includes(normalized)) return "journalist";
  if (["customer", "client", "клиент", "пользователь"].includes(normalized)) return "customer";
  if (["neutral", "нейтральный", "нейтральная"].includes(normalized)) return "neutral";
  return fallback;
}

